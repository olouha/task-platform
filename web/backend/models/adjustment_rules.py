from datetime import datetime
from typing import Dict, List, Optional, Any, Union
from pydantic import BaseModel, Field
from enum import Enum


# ============================================================
# 枚举定义
# ============================================================

class AdjustmentType(str, Enum):
    """是否必调"""
    REQUIRED = "必选"
    OPTIONAL = "可选"
    NONE = "不调整"


class RiskType(str, Enum):
    """风险幅度类型"""
    PERCENTAGE = "百分比"
    FIXED = "固定金额"
    NONE = "无"


class PhaseType(str, Enum):
    """是否分阶段调差"""
    YES = "是"
    NO = "否"


class FormulaType(str, Enum):
    """调差公式模板"""
    STANDARD_THREE_STAGE = "标准三段式"           # 标准三段式（最常用）
    NO_RISK = "无风险幅度"                         # 全额调差（0%风险幅度）
    RATIO_ADJUSTMENT = "比例调差法"               # 豪森模式
    COST_INFO_ADJUSTMENT = "造价信息调整法"       # 朱家庄模式
    LONGHU_VAT_CONVERSION = "龙湖增值税率换算法"  # 龙湖模式（含税/不含税换算）
    CUSTOM = "自定义"


class NegativeHandling(str, Enum):
    """负数处理（跌价）"""
    DEDUCT = "扣回"
    NO_ADJUST = "不调整"
    ACTUAL = "按实计算"


class PriceSource(str, Enum):
    """基准价来源"""
    COST_INFO = "造价信息"
    MYSTeel = "我的钢铁网"
    SHFE = "上海有色网"
    BID_PRICE = "投标价"
    CONTRACT_PRICE = "合同约定价"


class PriceRounding(str, Enum):
    """价格取整规则"""
    INTEGER = "取整到元"
    TWO_DECIMAL = "保留2位小数"


class HolidayHandling(str, Enum):
    """节假日/无价处理规则"""
    SHIFT_DAY = "顺延1天"
    AVERAGE_PREV_NEXT = "取前后日均价"
    LAST_MONTH = "取上月价"


class ShortCycleHandling(str, Enum):
    """短周期处理"""
    MERGE_ADJACENT = "并入相邻月份"
    EXCLUDE = "不计入"


class SupplyType(str, Enum):
    """供货方式"""
    B_TYPE = "乙供"  # 乙方供货
    A_TYPE = "甲供"  # 甲方供货
    A_REFERENCED_B = "甲指乙供"  # 甲方指定乙方供货


# ============================================================
# 子配置模型
# ============================================================

class SupplyPermission(BaseModel):
    """供货方式调差权限"""
    乙供: bool = True
    甲供: bool = False
    甲指乙供: bool = True


class DelayHandling(BaseModel):
    """工期延误处理"""
    承包人原因: str = "取低价"
    发包人原因: str = "按实调"


class PhaseDefinition(BaseModel):
    """阶段定义"""
    名称: str
    起始点: str
    结束点: str


class MaterialConfig(BaseModel):
    """单个材料配置"""
    名称: str
    是否必调: AdjustmentType
    调差范围: str = "仅调材料原价"  # 费用口径
    工程量范围: str = "全部"  # 可参与调差部位
    工程量计算规则: Optional[str] = None
    供货方式调差权限: Optional[SupplyPermission] = None
    变更签证是否参与: Optional[str] = "否"
    业态例外规则: Optional[str] = None


class RiskConfig(BaseModel):
    """风险幅度配置"""
    类型: RiskType
    值: float = 0.0  # 百分比值(%)或固定金额(元)


class PeriodPriceRule(BaseModel):
    """施工期价格采集规则"""
    采集方式: str = "按月算术平均"  # "每月1/10/20日取价"、"按月算术平均"等


# ============================================================
# 主配置模型
# ============================================================

class AdjustmentRuleConfig(BaseModel):
    """调差规则配置主模型"""
    # 元信息
    id: Optional[str] = None
    项目名称: str
    使用规则版本: str = "v2.0"
    is_preset: bool = False

    # 1. 基础信息类（4项）
    调差项目: List[MaterialConfig] = []

    # 2. 价格规则类（6项）
    风险幅度: Dict[str, RiskConfig] = {}  # 按材料名称索引
    基准价来源: Optional[PriceSource] = None
    基准价取价规则: Optional[str] = None
    施工期价格采集规则: Optional[Union[str, Dict[str, str]]] = "按月算术平均"  # 支持字符串或字典
    节假日无价处理规则: HolidayHandling = HolidayHandling.SHIFT_DAY
    价格取整规则: PriceRounding = PriceRounding.TWO_DECIMAL
    价格信息来源: Optional[str] = None  # 补充说明价格来源

    # 3. 周期与阶段类（5项）
    是否分阶段调差: PhaseType = PhaseType.NO
    阶段划分: List[PhaseDefinition] = []
    阶段起始点: Optional[str] = None
    阶段结束点: Optional[str] = None
    短周期处理: ShortCycleHandling = ShortCycleHandling.MERGE_ADJACENT
    阶段界限说明: Optional[str] = None  # 龙湖模式用

    # 4. 计算公式类（4项）
    调差公式模板: FormulaType = FormulaType.STANDARD_THREE_STAGE
    税率: float = 9.0  # 增值税率%
    负数处理: NegativeHandling = NegativeHandling.DEDUCT
    取费规则: str = "只计税金"

    # 龙湖模式专用字段（含税/不含税换算）
    增值税率: Optional[float] = None  # 13% 用于龙湖模式
    合同税率: Optional[float] = None  # 合同约定的增值税率
    钢筋调差公式: Optional[str] = None  # 自定义公式说明
    混凝土涨幅公式: Optional[str] = None
    混凝土跌幅公式: Optional[str] = None
    混凝土特殊规则: Optional[str] = None  # 甲方代付价+12.5元/m³采保费
    电缆调差规则: Optional[str] = None  # 铜价波动规则

    # 5. 特殊规则类（5项）
    供货方式调差权限: Optional[SupplyPermission] = None
    工期延误处理: Optional[DelayHandling] = None
    工程量计算规则: Optional[str] = None
    变更签证是否参与: Optional[str] = "否"
    业态例外规则: Optional[str] = None

    # 时间戳
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None

    class Config:
        use_enum_values = True


# ============================================================
# 计算结果模型（标准输出格式）
# ============================================================

class AdjustmentDetail(BaseModel):
    """调差明细 - 遵循v2.0输出格式标准"""
    材料名称: str
    阶段: str = "整体"
    工程量: float
    工程量单位: str
    基准价: float
    施工均价: float
    风险幅度: str  # 如"±3%"、"±1000元/吨"、"0%全额调差"
    是否超幅: bool
    调整单价: float  # 每单位调差金额（不含税）
    调整金额: float  # 不含税调差金额
    税率: float
    含税调整金额: float
    计算公式: str
    计算依据: str


class CalculationResult(BaseModel):
    """调差计算结果 - 遵循v2.0输出格式标准

    扩展字段（优化版）：
    - 不含税总金额: 不含税调差总金额
    - 税金: 调差税金（=不含税总金额 × 税率）
    - 阶段汇总: 按施工阶段分组的金额小计
    - 价格校验: 价格数据完整性检查结果
    """
    项目名称: str
    调差总金额: float
    不含税总金额: float = 0  # 不含税调差总金额
    税金: float = 0  # 调差税金 = 不含税总金额 × 税率
    明细: List[AdjustmentDetail] = []
    使用规则版本: str = "v2.0"
    计算时间: datetime = Field(default_factory=datetime.now)
    # 分阶段汇总
    阶段汇总: List[Dict[str, Any]] = []
    # 价格数据校验结果
    价格校验: Optional[Dict[str, Any]] = None

    class Config:
        use_enum_values = True


